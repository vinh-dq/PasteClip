import AppKit
import Combine

/// A record that sync mirrors: one clip or one pinboard.
public enum SyncRecord: Hashable {
    case clip(UUID)
    case pinboard(UUID)
}

/// Watches the pasteboard and keeps a persisted history of clips, the user's pinboards
/// and the paste stack. Clips are always ordered newest first.
public final class ClipStore: ObservableObject {
    @Published public private(set) var items: [ClipItem] = []
    @Published public private(set) var pinboards: [Pinboard] = []
    @Published public var paused = false

    /// Clips waiting to be pasted in order, oldest first. Local to this Mac.
    @Published public private(set) var stack: [UUID] = []
    /// While on, every new clip is also added to the end of the stack. Turning it off empties the stack.
    @Published public var stackMode = false {
        didSet { if !stackMode { stack.removeAll() } }
    }

    public var historyLimit = 500 { didSet { limitsChanged() } }
    /// 0 keeps history forever.
    public var retentionDays = 0 { didSet { limitsChanged() } }
    /// Copies made while one of these apps is frontmost are not recorded.
    public var excludedBundleIDs: Set<String> = []
    /// Skip clips that password managers mark as concealed.
    public var skipConcealed = true
    /// Skip clips that apps mark as transient or auto-generated.
    public var skipTransient = true
    /// Look for text in image clips with Vision.
    public var recognizesText = true
    /// Languages to look for in images, most likely first.
    public var recognitionLanguages = TextRecognizer.defaultLanguages
    /// While true, clipboard changes are let go by, as when PasteClip copies the selection in
    /// another app to read it and then puts the clipboard back.
    public var captureSuspended = false {
        didSet { if !captureSuspended { lastChangeCount = pasteboard.changeCount } }
    }

    /// Called after a clip is captured from the pasteboard.
    public var onCapture: ((ClipItem) -> Void)?
    /// Called after a local edit, with the records to upload and to delete. Remote changes don't trigger it.
    public var onLocalChange: ((_ saved: [SyncRecord], _ deleted: [SyncRecord]) -> Void)?

    public let directory: URL
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?
    private let imageDir: URL
    private let richDir: URL
    private let imageCache = NSCache<NSString, NSImage>()
    private let ioQueue = DispatchQueue(label: "PasteClip.ClipStore.io", qos: .utility)
    /// Latest state waiting to be written. Only touched on ioQueue.
    private var unsaved: ([ClipItem], [Pinboard])?

    /// - Parameters:
    ///   - directory: Where history is stored. Defaults to `~/Library/Application Support/PasteClip`.
    ///   - pasteboard: The pasteboard to watch. Tests pass a private named pasteboard.
    public init(directory: URL? = nil, pasteboard: NSPasteboard = .general) {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
        self.pasteboard = pasteboard
        self.directory = directory ?? support.appendingPathComponent("PasteClip", isDirectory: true)
        imageDir = self.directory.appendingPathComponent("images", isDirectory: true)
        richDir = self.directory.appendingPathComponent("rich", isDirectory: true)
        try? FileManager.default.createDirectory(at: imageDir, withIntermediateDirectories: true)
        try? FileManager.default.createDirectory(at: richDir, withIntermediateDirectories: true)
        lastChangeCount = pasteboard.changeCount
        load()
    }

    public func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { [weak self] _ in
            self?.poll()
        }
        timer?.tolerance = 0.1
    }

    // MARK: - Capture

    func poll() {
        guard pasteboard.changeCount != lastChangeCount else { return }
        lastChangeCount = pasteboard.changeCount
        guard !paused, !captureSuspended else { return }

        let types = pasteboard.types ?? []
        // Respect password managers and other apps that mark data as private or temporary
        // (https://nspasteboard.org).
        let marks = Set(types.map(\.rawValue))
        if skipConcealed, marks.contains("org.nspasteboard.ConcealedType") { return }
        if skipTransient, !marks.isDisjoint(with: ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]) { return }

        let front = NSWorkspace.shared.frontmostApplication
        if front?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        if let id = front?.bundleIdentifier, excludedBundleIDs.contains(id) { return }

        guard var item = capture(types: types) else { return }
        item.sourceBundleID = front?.bundleIdentifier
        item.sourceName = front?.localizedName
        let stored = insert(item)
        onCapture?(stored)
    }

    private func capture(types: [NSPasteboard.PasteboardType]) -> ClipItem? {
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return ClipItem(kind: .file, filePaths: urls.map(\.path))
        }
        if let string = pasteboard.string(forType: .string), !Self.isBlank(string) {
            return textItem(string, rich: richData(in: types))
        }
        if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           let image = NSImage(data: data),
           let png = image.pngData {
            var item = ClipItem(kind: .image)
            let name = "\(item.id.uuidString).png"
            guard (try? png.write(to: imageDir.appendingPathComponent(name))) != nil else { return nil }
            item.imageFile = name
            return item
        }
        // Some apps copy only formatted text, with no plain version alongside.
        if let rich = richData(in: types), let string = Self.attributedString(from: rich.0, type: rich.1)?.string,
           !Self.isBlank(string.replacingOccurrences(of: "\u{FFFC}", with: "")) {
            return textItem(string, rich: rich)
        }
        return nil
    }

    private static func isBlank(_ string: String) -> Bool {
        string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty
    }

    /// A text clip, keeping its formatting. Links keep theirs too: a linked URL can carry a
    /// different label or style in the app it came from.
    private func textItem(_ string: String, rich: (Data, String)?) -> ClipItem {
        var item = ClipItem(kind: ClipKind.detect(string), text: string)
        let contents = item.kind == .color ? nil : pasteboardContents()
        var rich = rich
        // Slack's own formatting, also kept as RTF so other apps get the bold and links.
        if rich == nil, let contents, let text = SlackFormatting.attributedString(from: contents),
           let rtf = Self.rtf(of: SlackFormatting.portable(text)) {
            rich = (rtf, "rtf")
        }
        if item.kind != .color, let (data, type) = rich {
            let name = "\(item.id.uuidString).\(type)"
            if (try? data.write(to: richDir.appendingPathComponent(name))) != nil {
                item.richFile = name
                item.richType = type
            }
        }
        if let contents { item.pasteboardFile = write(contents, name: "\(item.id.uuidString).pasteboard") }
        return item
    }

    private func write(_ contents: [[String: Data]], name: String) -> String? {
        guard let data = try? PropertyListSerialization.data(fromPropertyList: contents, format: .binary, options: 0),
              (try? data.write(to: richDir.appendingPathComponent(name))) != nil else { return nil }
        return name
    }

    /// The clip's text with its formatting, for showing and editing. Slack's own formatting comes
    /// first, as only it has mentions. HTML is parsed with WebKit, so call this on the main thread.
    public func formattedText(for item: ClipItem) -> NSAttributedString? {
        if let contents = pasteboardContents(for: item), let text = SlackFormatting.attributedString(from: contents) {
            return text
        }
        guard let (data, type) = richData(for: item) else { return nil }
        return Self.attributedString(from: data, type: type)
    }

    /// Plain text, RTF and HTML under their own and their legacy names: `text` and `richFile`
    /// already hold those.
    private static let plainTypes: Set<String> = [
        "public.utf8-plain-text", "public.utf16-plain-text", "public.utf16-external-plain-text",
        "public.plain-text", "public.text", "com.apple.traditional-mac-plain-text", "NSStringPboardType",
        "public.rtf", "NeXT Rich Text Format v1.0 pasteboard type", "public.html", "Apple HTML pasteboard type",
    ]
    private static let maxPasteboardBytes = 20 << 20

    /// Every type on the pasteboard, item by item, when there's more to it than plain text,
    /// RTF and HTML: apps such as Slack, VS Code and Office keep their formatting in types of
    /// their own and read only those back. Markers like "concealed" are left out, and so is
    /// anything too large.
    private func pasteboardContents() -> [[String: Data]]? {
        guard let items = pasteboard.pasteboardItems, !items.isEmpty else { return nil }
        let types = items.flatMap { $0.types.map(\.rawValue) }
        // `dyn.` types are aliases the system makes up for old type names.
        let extra = types.contains { !Self.plainTypes.contains($0) && !$0.hasPrefix("dyn.") && !$0.hasPrefix("org.nspasteboard.") }
        guard items.count > 1 || extra else { return nil }
        var total = 0
        let contents = items.map { item in
            var entry: [String: Data] = [:]
            for type in item.types where !type.rawValue.hasPrefix("org.nspasteboard.") {
                guard let data = item.data(forType: type), total + data.count <= Self.maxPasteboardBytes else { continue }
                total += data.count
                entry[type.rawValue] = data
            }
            return entry
        }
        return contents.contains { !$0.isEmpty } ? contents : nil
    }

    /// What `pasteboardFile` holds.
    func pasteboardContents(for item: ClipItem) -> [[String: Data]]? {
        guard let name = item.pasteboardFile,
              let data = try? Data(contentsOf: richDir.appendingPathComponent(name)) else { return nil }
        return try? PropertyListSerialization.propertyList(from: data, format: nil) as? [[String: Data]]
    }

    /// The copied formatting, as RTF or HTML. RTFD (Notes, Pages, TextEdit with pictures) is kept
    /// as RTF: its text formatting and links survive, its pictures don't.
    private func richData(in types: [NSPasteboard.PasteboardType]) -> (Data, String)? {
        if types.contains(.rtf), let data = pasteboard.data(forType: .rtf) { return (data, "rtf") }
        if types.contains(.rtfd), let data = pasteboard.data(forType: .rtfd),
           let text = NSAttributedString(rtfd: data, documentAttributes: nil),
           let rtf = Self.rtf(of: text) {
            return (rtf, "rtf")
        }
        if types.contains(.html), let data = pasteboard.data(forType: .html) { return (data, "html") }
        return nil
    }

    /// Parses formatted text stored as `rtf` or `html`. HTML is parsed with WebKit, so call that on the main thread.
    public static func attributedString(from data: Data, type: String) -> NSAttributedString? {
        type == "rtf" ? NSAttributedString(rtf: data, documentAttributes: nil)
                      : NSAttributedString(html: data, documentAttributes: nil)
    }

    static func rtf(of text: NSAttributedString) -> Data? {
        text.rtf(from: NSRange(location: 0, length: text.length), documentAttributes: [:])
    }

    /// Adds a clip at the top. A clip with the same content is moved up instead, keeping its
    /// id, title, pin and pinboard. Returns the clip as stored.
    @discardableResult
    func insert(_ item: ClipItem) -> ClipItem {
        var item = item
        if item.kind != .image,
           let i = items.firstIndex(where: { $0.kind == item.kind && $0.contentKey == item.contentKey }) {
            var existing = items.remove(at: i)
            existing.date = item.date
            existing.sourceBundleID = item.sourceBundleID ?? existing.sourceBundleID
            existing.sourceName = item.sourceName ?? existing.sourceName
            // A copy with formatting replaces the old formatting; a plain copy of the same text keeps it.
            if item.hasFormatting {
                deleteFormatting(of: existing)
                existing.richFile = item.richFile
                existing.richType = item.richType
                existing.pasteboardFile = item.pasteboardFile
            }
            item = existing
        }
        items.insert(item, at: 0)
        if stackMode {
            stack.removeAll { $0 == item.id }
            stack.append(item.id)
        }
        let removed = applyLimits()
        save()
        notify(saved: [.clip(item.id)], deleted: removed)
        if item.kind == .image, item.ocrText == nil { recognizeText(in: item) }
        return item
    }

    /// Reads the text in an image clip or a copied image file now, whatever the setting, keeps it
    /// with the clip (so it can be searched and is ready next time) and hands it over. A clip that
    /// already has its text gets it straight back.
    public func readText(in item: ClipItem, completion: @escaping (String?) -> Void) {
        if let text = item.ocrText { return completion(text) }
        guard item.isImage, let url = pictureURL(for: item) else { return completion(nil) }
        TextRecognizer.recognize(imageAt: url, languages: recognitionLanguages) { [weak self] text in
            if let self, let text, let i = self.index(of: item.id) {
                self.items[i].ocrText = text
                self.save()
                self.notify(saved: [.clip(item.id)], deleted: [])
            }
            completion(text)
        }
    }

    private func recognizeText(in item: ClipItem) {
        guard recognizesText, let url = imageURL(for: item) else { return }
        TextRecognizer.recognize(imageAt: url, languages: recognitionLanguages) { [weak self] text in
            guard let self, let text, let i = self.index(of: item.id) else { return }
            self.items[i].ocrText = text
            self.save()
            self.notify(saved: [.clip(item.id)], deleted: [])
        }
    }

    private func limitsChanged() {
        let removed = applyLimits()
        guard !removed.isEmpty else { return }
        save()
        notify(saved: [], deleted: removed)
    }

    /// Drops unkept clips beyond the history limit or older than the retention period.
    private func applyLimits() -> [SyncRecord] {
        let cutoff = retentionDays > 0 ? Date().addingTimeInterval(-Double(retentionDays) * 86_400) : nil
        var count = 0
        var removed: [ClipItem] = []
        items = items.filter { item in
            if item.isKept { return true }
            count += 1
            if count > historyLimit || cutoff.map({ item.date < $0 }) == true {
                removed.append(item)
                return false
            }
            return true
        }
        removed.forEach(deleteFiles)
        let ids = Set(removed.map(\.id))
        stack.removeAll { ids.contains($0) }
        return ids.map { .clip($0) }
    }

    // MARK: - Clip actions

    public func item(withID id: UUID) -> ClipItem? {
        items.first { $0.id == id }
    }

    private func index(of id: UUID) -> Int? {
        items.firstIndex { $0.id == id }
    }

    /// Puts the clip back on the pasteboard without re-recording it, and moves it to the top.
    public func copyToPasteboard(_ item: ClipItem, plainText: Bool = false) {
        pasteboard.clearContents()
        switch item.kind {
        case .text, .link, .color:
            if !plainText, let contents = pasteboardContents(for: item) {
                // Exactly what the source app copied, plus HTML for browsers if it had only RTF.
                let extra = richRepresentations(for: item)
                let entries = contents.enumerated().map { n, entry in
                    let pasteboardItem = NSPasteboardItem()
                    for (type, data) in entry { pasteboardItem.setData(data, forType: .init(type)) }
                    if n == 0 {
                        if entry[NSPasteboard.PasteboardType.string.rawValue] == nil {
                            pasteboardItem.setString(item.text ?? "", forType: .string)
                        }
                        for (type, data) in extra where entry[type.rawValue] == nil { pasteboardItem.setData(data, forType: type) }
                    }
                    return pasteboardItem
                }
                pasteboard.writeObjects(entries)
            } else {
                pasteboard.setString(item.text ?? "", forType: .string)
                if !plainText {
                    for (type, data) in richRepresentations(for: item) { pasteboard.setData(data, forType: type) }
                }
            }
        case .image:
            if plainText, let text = item.ocrText {
                pasteboard.setString(text, forType: .string)
            } else if let image = image(for: item) {
                pasteboard.writeObjects([image])
            }
        case .file:
            if plainText {
                pasteboard.setString(item.contentKey, forType: .string)
            } else {
                pasteboard.writeObjects((item.filePaths ?? []).map { URL(fileURLWithPath: $0) as NSURL })
            }
        }
        lastChangeCount = pasteboard.changeCount
        guard let i = index(of: item.id) else { return }
        var moved = items.remove(at: i)
        moved.date = Date()
        items.insert(moved, at: 0)
        save()
        notify(saved: [.clip(item.id)], deleted: [])
    }

    /// Puts several clips on the pasteboard to paste together, in the order given. Text goes as
    /// one text, a line apart (plain: their formatting doesn't join up); files go together; a mix
    /// with images goes as one pasteboard item per clip. Plain text also turns images into the text
    /// found in them and files into their paths. The clips move to the top, keeping their order.
    public func copyToPasteboard(_ items: [ClipItem], plainText: Bool = false) {
        guard items.count > 1 else {
            if let item = items.first { copyToPasteboard(item, plainText: plainText) }
            return
        }
        pasteboard.clearContents()
        let texts = items.map { item -> String? in
            switch item.kind {
            case .text, .link, .color: return item.text
            case .image: return plainText ? item.ocrText : nil
            case .file: return plainText ? item.contentKey : nil
            }
        }
        if !plainText, items.allSatisfy({ $0.kind == .file }) {
            pasteboard.writeObjects(items.flatMap { $0.filePaths ?? [] }.map { URL(fileURLWithPath: $0) as NSURL })
        } else if texts.allSatisfy({ $0 != nil }) {
            pasteboard.setString(texts.compactMap { $0 }.joined(separator: "\n"), forType: .string)
        } else {
            pasteboard.writeObjects(items.compactMap { item -> NSPasteboardItem? in
                let entry = NSPasteboardItem()
                switch item.kind {
                case .text, .link, .color: entry.setString(item.text ?? "", forType: .string)
                case .image:
                    guard let png = image(for: item)?.pngData else { return nil }
                    entry.setData(png, forType: .png)
                case .file:
                    guard let path = item.filePaths?.first else { return nil }
                    entry.setString(URL(fileURLWithPath: path).absoluteString, forType: .fileURL)
                }
                return entry
            })
        }
        lastChangeCount = pasteboard.changeCount
        let now = Date()
        for (n, item) in items.enumerated().reversed() {
            guard let i = index(of: item.id) else { continue }
            var moved = self.items.remove(at: i)
            // A moment apart, so sorting by date keeps them in this order.
            moved.date = now.addingTimeInterval(-Double(n) / 1000)
            self.items.insert(moved, at: 0)
        }
        save()
        notify(saved: items.map { .clip($0.id) }, deleted: [])
    }

    /// Puts text on the clipboard without adding it to history.
    public func copyWithoutSaving(_ text: String) {
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        lastChangeCount = pasteboard.changeCount
    }

    /// Puts an image on the clipboard without adding it to history, to paste somewhere once.
    public func copyImageWithoutSaving(_ png: Data) {
        pasteboard.clearContents()
        pasteboard.setData(png, forType: .png)
        if let tiff = NSImage(data: png)?.tiffRepresentation { pasteboard.setData(tiff, forType: .tiff) }
        lastChangeCount = pasteboard.changeCount
    }

    /// Adds a text clip typed by the user, or read from the screen.
    @discardableResult
    public func addText(_ text: String, title: String? = nil, source: String = "PasteClip") -> ClipItem? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return nil }
        var item = ClipItem(kind: ClipKind.detect(text), text: text, sourceBundleID: Bundle.main.bundleIdentifier,
                            sourceName: source)
        item.title = title
        return insert(item)
    }

    /// Adds an image clip made in PasteClip, such as an edited copy of another image.
    @discardableResult
    public func addImage(_ png: Data, title: String? = nil, source: String = "PasteClip") -> ClipItem? {
        var item = ClipItem(kind: .image, sourceBundleID: Bundle.main.bundleIdentifier, sourceName: source)
        let name = "\(item.id.uuidString).png"
        guard (try? png.write(to: imageDir.appendingPathComponent(name))) != nil else { return nil }
        item.imageFile = name
        item.title = title
        return insert(item)
    }

    public func togglePin(_ item: ClipItem) {
        update(item.id) { $0.pinned.toggle() }
    }

    public func setTitle(_ item: ClipItem, _ title: String) {
        let t = title.trimmingCharacters(in: .whitespacesAndNewlines)
        update(item.id) { $0.title = t.isEmpty ? nil : t }
    }

    /// Replaces the text of a text, link or colour clip. Formatting is dropped and the kind re-detected.
    public func updateText(_ item: ClipItem, _ text: String) {
        guard item.isTextual, !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              let current = self.item(withID: item.id), current.text != text else { return }
        deleteFormatting(of: current)
        update(item.id) {
            $0.text = text
            $0.kind = ClipKind.detect(text)
            $0.richFile = nil
            $0.richType = nil
            $0.pasteboardFile = nil
        }
    }

    /// Replaces the text of a clip with formatted text, saved as RTF so styles and links are kept.
    public func updateText(_ item: ClipItem, _ text: NSAttributedString) {
        guard item.isTextual, !Self.isBlank(text.string), let current = self.item(withID: item.id) else { return }
        guard let data = Self.rtf(of: SlackFormatting.portable(text)) else { return updateText(item, text.string) }
        // New names for every edit, so views that cache the formatting by file see the change.
        let stem = "\(item.id.uuidString)-\(UUID().uuidString.prefix(8))"
        guard (try? data.write(to: richDir.appendingPathComponent("\(stem).rtf"))) != nil else { return }
        // Slack's formatting is rewritten with the new text; other apps' own formats still hold
        // the old text, so they go.
        let appFormats = pasteboardContents(for: current)
            .flatMap { SlackFormatting.contents($0, replacingTextWith: text) }
            .flatMap { write($0, name: "\(stem).pasteboard") }
        deleteFormatting(of: current)
        update(item.id) {
            $0.text = text.string
            $0.kind = ClipKind.detect(text.string)
            $0.richFile = "\(stem).rtf"
            $0.richType = "rtf"
            $0.pasteboardFile = appFormats
        }
    }

    public func delete(_ item: ClipItem) {
        delete([item])
    }

    /// Deletes several clips at once, saving once.
    public func delete(_ items: [ClipItem]) {
        let ids = Set(items.map(\.id))
        let current = self.items.filter { ids.contains($0.id) }
        guard !current.isEmpty else { return }
        current.forEach(deleteFiles(of:))
        self.items.removeAll { ids.contains($0.id) }
        stack.removeAll { ids.contains($0) }
        save()
        notify(saved: [], deleted: current.map { .clip($0.id) })
    }

    public func clearHistory() {
        let removed = items.filter { !$0.isKept }
        removed.forEach(deleteFiles)
        items.removeAll { !$0.isKept }
        stack.removeAll { id in removed.contains { $0.id == id } }
        save()
        notify(saved: [], deleted: removed.map { .clip($0.id) })
    }

    private func update(_ id: UUID, _ change: (inout ClipItem) -> Void) {
        guard let i = index(of: id) else { return }
        change(&items[i])
        save()
        notify(saved: [.clip(id)], deleted: [])
    }

    // MARK: - Pinboards

    @discardableResult
    public func createPinboard(name: String, colorIndex: Int) -> Pinboard {
        var board = Pinboard(name: name, colorIndex: colorIndex)
        // Once the user has ordered the pinboards, new ones go at the end.
        if let last = pinboards.compactMap(\.order).max() { board.order = last + 1 }
        pinboards.append(board)
        save()
        notify(saved: [.pinboard(board.id)], deleted: [])
        return board
    }

    public func updatePinboard(_ board: Pinboard) {
        guard let i = pinboards.firstIndex(where: { $0.id == board.id }) else { return }
        pinboards[i] = board
        save()
        notify(saved: [.pinboard(board.id)], deleted: [])
    }

    /// Deletes the pinboard. Its clips stay in history.
    public func deletePinboard(_ board: Pinboard) {
        pinboards.removeAll { $0.id == board.id }
        var changed: [SyncRecord] = []
        for i in items.indices where items[i].pinboardID == board.id {
            items[i].pinboardID = nil
            changed.append(.clip(items[i].id))
        }
        save()
        notify(saved: changed, deleted: [.pinboard(board.id)])
    }

    /// Moves the pinboard to `index` among the pinboards.
    public func movePinboard(_ id: UUID, to index: Int) {
        guard let from = pinboards.firstIndex(where: { $0.id == id }) else { return }
        let board = pinboards.remove(at: from)
        pinboards.insert(board, at: min(max(index, 0), pinboards.count))
        for i in pinboards.indices { pinboards[i].order = Double(i) }
        save()
        notify(saved: pinboards.map { .pinboard($0.id) }, deleted: [])
    }

    /// Moves a clip onto a pinboard, at the front, or off any pinboard when `board` is nil.
    public func setPinboard(_ item: ClipItem, _ board: Pinboard?) {
        guard item.pinboardID != board?.id else { return }
        let front = board.map { b in items.filter { $0.pinboardID == b.id }.map(\.boardKey).min() ?? 0 }
        update(item.id) {
            $0.pinboardID = board?.id
            $0.boardOrder = front.map { $0 - 1 }
        }
    }

    /// Moves a clip on its pinboard to where `target` is, shifting the clips in between.
    public func moveClip(_ id: UUID, to target: UUID) {
        guard id != target, let board = item(withID: id)?.pinboardID,
              item(withID: target)?.pinboardID == board else { return }
        var ordered = items.enumerated().filter { $0.element.pinboardID == board }
            .sorted { ($0.element.boardKey, $0.offset) < ($1.element.boardKey, $1.offset) }
            .map(\.element.id)
        guard let from = ordered.firstIndex(of: id), let to = ordered.firstIndex(of: target) else { return }
        ordered.remove(at: from)
        ordered.insert(id, at: to)
        // Renumber from the current front, so clips added later still go before these.
        let base = items.filter { $0.pinboardID == board }.map(\.boardKey).min() ?? 0
        let position = Dictionary(uniqueKeysWithValues: ordered.enumerated().map { ($1, base + Double($0)) })
        var changed: [SyncRecord] = []
        for i in items.indices {
            guard let p = position[items[i].id], items[i].boardOrder != p else { continue }
            items[i].boardOrder = p
            changed.append(.clip(items[i].id))
        }
        save()
        notify(saved: changed, deleted: [])
    }

    // MARK: - Paste stack

    public var stackItems: [ClipItem] {
        stack.compactMap(item(withID:))
    }

    public func addToStack(_ item: ClipItem) {
        stack.removeAll { $0 == item.id }
        stack.append(item.id)
    }

    public func removeFromStack(_ item: ClipItem) {
        stack.removeAll { $0 == item.id }
    }

    /// Takes the next clip off the stack.
    public func popStack() -> ClipItem? {
        while !stack.isEmpty {
            if let item = item(withID: stack.removeFirst()) { return item }
        }
        return nil
    }

    // MARK: - Files

    public func image(for item: ClipItem) -> NSImage? {
        guard let name = item.imageFile else { return nil }
        if let cached = imageCache.object(forKey: name as NSString) { return cached }
        guard let image = NSImage(contentsOf: imageDir.appendingPathComponent(name)) else { return nil }
        imageCache.setObject(image, forKey: name as NSString)
        return image
    }

    public func imageURL(for item: ClipItem) -> URL? {
        item.imageFile.map { imageDir.appendingPathComponent($0) }
    }

    /// Where the picture of an image clip or a copied image file is.
    public func pictureURL(for item: ClipItem) -> URL? {
        imageURL(for: item) ?? item.copiedImagePath.map { URL(fileURLWithPath: $0) }
    }

    public func richURL(for item: ClipItem) -> URL? {
        item.richFile.map { richDir.appendingPathComponent($0) }
    }

    /// The formatted text and its type (`rtf` or `html`), if the clip has any.
    public func richData(for item: ClipItem) -> (Data, String)? {
        guard let url = richURL(for: item), let type = item.richType,
              let data = try? Data(contentsOf: url) else { return nil }
        return (data, type)
    }

    /// The clip's formatting for the pasteboard. RTF is offered as HTML too, since browsers read
    /// only HTML; converting is quick. HTML is left as it is: most apps read it, and turning it
    /// into RTF goes through WebKit, which can take a second and would hold up the paste.
    public func richRepresentations(for item: ClipItem) -> [NSPasteboard.PasteboardType: Data] {
        guard let (data, type) = richData(for: item) else { return [:] }
        guard type == "rtf" else { return [.html: data] }
        let html = NSAttributedString(rtf: data, documentAttributes: nil).flatMap { text in
            try? text.data(from: NSRange(location: 0, length: text.length),
                           documentAttributes: [.documentType: NSAttributedString.DocumentType.html])
        }
        return [.rtf: data, .html: html].compactMapValues { $0 }
    }

    private func deleteFiles(of item: ClipItem) {
        if let name = item.imageFile {
            try? FileManager.default.removeItem(at: imageDir.appendingPathComponent(name))
            imageCache.removeObject(forKey: name as NSString)
        }
        deleteFormatting(of: item)
    }

    private func deleteFormatting(of item: ClipItem) {
        if let url = richURL(for: item) { try? FileManager.default.removeItem(at: url) }
        if let name = item.pasteboardFile { try? FileManager.default.removeItem(at: richDir.appendingPathComponent(name)) }
    }

    // MARK: - Sync

    public var allSyncRecords: [SyncRecord] {
        pinboards.map { .pinboard($0.id) } + items.map { .clip($0.id) }
    }

    public func pinboard(withID id: UUID) -> Pinboard? {
        pinboards.first { $0.id == id }
    }

    /// Stores a clip that came from another Mac. Asset files are copied into the store.
    public func applyRemote(_ remote: ClipItem, imageSource: URL?, richSource: URL?) {
        var item = remote
        let old = self.item(withID: item.id)
        item.imageFile = copyIn(imageSource, to: imageDir, name: "\(item.id.uuidString).png") ?? old?.imageFile
        if let type = item.richType {
            item.richFile = copyIn(richSource, to: richDir, name: "\(item.id.uuidString).\(type)") ?? old?.richFile
        } else {
            item.richFile = nil
        }
        // The source app's formats aren't synced; they stay while the text is unchanged.
        if let old, old.text == item.text {
            item.pasteboardFile = old.pasteboardFile
        } else if let old, let name = old.pasteboardFile {
            try? FileManager.default.removeItem(at: richDir.appendingPathComponent(name))
        }
        if let name = item.imageFile { imageCache.removeObject(forKey: name as NSString) }
        items.removeAll { $0.id == item.id }
        let at = items.firstIndex { $0.date < item.date } ?? items.endIndex
        items.insert(item, at: at)
        save()
    }

    public func removeRemoteClip(_ id: UUID) {
        guard let item = item(withID: id) else { return }
        deleteFiles(of: item)
        items.removeAll { $0.id == id }
        stack.removeAll { $0 == id }
        save()
    }

    public func applyRemote(_ board: Pinboard) {
        if let i = pinboards.firstIndex(where: { $0.id == board.id }) {
            pinboards[i] = board
        } else {
            pinboards.append(board)
        }
        pinboards.sort { ($0.order ?? .infinity, $0.created) < ($1.order ?? .infinity, $1.created) }
        save()
    }

    public func removeRemotePinboard(_ id: UUID) {
        pinboards.removeAll { $0.id == id }
        for i in items.indices where items[i].pinboardID == id { items[i].pinboardID = nil }
        save()
    }

    private func copyIn(_ source: URL?, to dir: URL, name: String) -> String? {
        guard let source else { return nil }
        let dest = dir.appendingPathComponent(name)
        try? FileManager.default.removeItem(at: dest)
        return (try? FileManager.default.copyItem(at: source, to: dest)) != nil ? name : nil
    }

    private func notify(saved: [SyncRecord], deleted: [SyncRecord]) {
        guard !saved.isEmpty || !deleted.isEmpty else { return }
        onLocalChange?(saved, deleted)
    }

    // MARK: - Persistence

    private var historyURL: URL { directory.appendingPathComponent("history.json") }
    private var pinboardsURL: URL { directory.appendingPathComponent("pinboards.json") }

    private func load() {
        if let data = try? Data(contentsOf: historyURL),
           let decoded = try? JSONDecoder().decode([ClipItem].self, from: data) {
            items = decoded.sorted { $0.date > $1.date }
        }
        if let data = try? Data(contentsOf: pinboardsURL),
           let decoded = try? JSONDecoder().decode([Pinboard].self, from: data) {
            pinboards = decoded
        }
    }

    /// Saves soon, off the main thread. Saves made close together are written once.
    private func save() {
        let snapshot = (items, pinboards)
        ioQueue.async { self.unsaved = snapshot }
        ioQueue.asyncAfter(deadline: .now() + 0.4) { self.writeUnsaved() }
    }

    /// Writes any pending changes now. Call before quitting.
    public func flush() {
        ioQueue.sync { writeUnsaved() }
    }

    // Runs on ioQueue.
    private func writeUnsaved() {
        guard let (items, pinboards) = unsaved else { return }
        unsaved = nil
        if let data = try? JSONEncoder().encode(items) {
            try? data.write(to: historyURL, options: .atomic)
        }
        if let data = try? JSONEncoder().encode(pinboards) {
            try? data.write(to: pinboardsURL, options: .atomic)
        }
    }
}

